class LiteBrowser {
  OS::IPCClient *ipc;
  char url_buffer[256];
  int url_len;
  uint8_t *page_buffer;
  int page_size;
  uint32_t bg_color, fg_color, bar_color;

  void draw_char(int x, int y, char c, uint32_t color) {
    if ((uint8_t)c >= 128) return;
    const uint8_t *glyph = font8x8[(uint8_t)c];
    for (int gy = 0; gy < 8; gy++) {
      for (int gx = 0; gx < 8; gx++) {
        if (glyph[gy] & (1 << (7 - gx))) {
          ipc->put_pixel(x + gx, y + gy, color);
        }
      }
    }
  }

  void draw_text(int x, int y, const char *text, uint32_t color) {
    while (*text) {
      draw_char(x, y, *text++, color);
      x += 8;
    }
  }

  void render() {
    ipc->fill_rect(0, 0, ipc->get_width(), ipc->get_height(), bg_color);
    
    // Draw Address Bar
    ipc->fill_rect(0, 0, ipc->get_width(), 32, bar_color);
    draw_text(10, 10, "URL: ", 0xFFFFFFFF);
    draw_text(50, 10, url_buffer, 0xFFFFFFFF);
    
    // Draw Page Content
    if (page_size > 0) {
      int x = 10;
      int y = 40;
      for (int i = 0; i < page_size; i++) {
        char c = (char)page_buffer[i];
        if (c == '\n') {
          x = 10;
          y += 10;
        } else if (c == '\r') {
          x = 10;
        } else {
          draw_char(x, y, c, fg_color);
          x += 8;
          if (x > ipc->get_width() - 10) {
            x = 10;
            y += 10;
          }
        }
        if (y > ipc->get_height() - 10) break;
      }
    } else if (page_size == -1) {
       draw_text(10, 40, "Loading...", 0xFFFFFF00);
    } else if (page_size == -2) {
       draw_text(10, 40, "Error: Failed to fetch page.", 0xFFFF0000);
    }

    ipc->flush();
  }

  void fetch_page() {
    page_size = -1;
    render();
    int res = OS::Syscall::http_get(url_buffer, page_buffer, 64 * 1024);
    if (res >= 0) {
      page_size = res;
    } else {
      page_size = -2;
    }
    render();
  }

public:
  LiteBrowser() : ipc(nullptr), url_len(0), page_size(0) {
    OS::String::strcpy(url_buffer, "http://example.com");
    url_len = 18;
    bg_color = 0xFF1E1E1E;
    fg_color = 0xFFCCCCCC;
    bar_color = 0xFF333333;
    page_buffer = (uint8_t*)OS::Syscall::sbrk(64 * 1024);
  }

  void run() {
    ipc = new OS::IPCClient();
    if (!ipc->connect()) return;
    if (!ipc->create_window("Retro-OS Lite Browser", 800, 600)) return;

    render();

    while (true) {
      OS::gfx_msg_t msg;
      while (ipc->recv_msg(&msg)) {
        if (msg.type == OS::MSG_GFX_KEY_EVENT) {
          char k = msg.data.key.key;
          if (k == '\r' || k == '\n' || k == 0x0D) {
            fetch_page();
          } else if (k == 0x08) { // Backspace
            if (url_len > 0) {
              url_buffer[--url_len] = '\0';
            }
          } else if (k >= 32 && k < 127) {
            if (url_len < 254) {
              url_buffer[url_len++] = k;
              url_buffer[url_len] = '\0';
            }
          }
          render();
        }
      }
      OS::Syscall::sleep(2);
    }
  }
};

extern "C" int main(int argc, char** argv) {
  init_font8x8();
  LiteBrowser browser;
  browser.run();
  return 0;
}
